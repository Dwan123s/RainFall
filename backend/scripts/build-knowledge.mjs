import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { syncFrontendShared } from './sync-frontend-shared.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const policy = readFileSync(path.join(root, 'docs/ai/rainsense-system-prompt.txt'), 'utf8').replace(/\r\n/g, '\n').trim();
if (policy.length < 1000 || !policy.includes('RainSense AI') || /GEMINI_API_KEY\s*=|WIFI_PASS\s*=|MQTT_PASSWORD\s*=|postgres(?:ql)?:\/\//i.test(policy)) throw new Error('Invalid chatbot policy');
const policyOutput = `// Generated from docs/ai/rainsense-system-prompt.txt by scripts/build-knowledge.mjs.\nexport const RAIN_SENSE_POLICY = ${JSON.stringify(policy)};\n`;
const policyTarget = path.join(root, 'backend/src/shared/policy.generated.ts');
let previousPolicy = '';
try { previousPolicy = readFileSync(policyTarget, 'utf8'); } catch { /* First build. */ }
if (previousPolicy !== policyOutput) writeFileSync(policyTarget, policyOutput, 'utf8');
const specTarget = path.join(root, 'docs/ai/realtime-chatbot-spec.md');
const spec = readFileSync(specTarget, 'utf8').replace(/\r\n/g, '\n');
if (!/```text\n[\s\S]*?\n```/.test(spec)) throw new Error('Missing system prompt in specification');
const updatedSpec = spec.replace(/```text\n[\s\S]*?\n```/, () => '```text\n' + policy + '\n```');
if (updatedSpec !== spec) writeFileSync(specTarget, updatedSpec, 'utf8');
const directory = path.join(root, 'docs/knowledge');
const chunks = [];
for (const name of readdirSync(directory).filter((n) => /^\d{2}-[a-z0-9-]+\.md$/.test(n)).sort()) {
  const text = readFileSync(path.join(directory, name), 'utf8').replace(/\r\n/g, '\n');
  const match = text.match(/^<!-- (\{[^\r\n]+\}) -->/);
  if (!match) throw new Error(`Missing knowledge metadata: ${name}`);
  const meta = JSON.parse(match[1]);
  if (!['verified', 'draft', 'deprecated'].includes(meta.status) || !meta.documentId || !meta.version || !meta.verifiedAt || !meta.title || !Array.isArray(meta.keywords) || !['all', 'unknown', 'oled-s3', 'rainsense-s3'].includes(meta.hardwareVariant)) throw new Error(`Invalid metadata: ${name}`);
  if (meta.status !== 'verified') continue;
  const body = text.slice(match[0].length).trim();
  if (/GEMINI_API_KEY\s*=|WIFI_PASS\s*=|MQTT_PASSWORD\s*=|postgres(?:ql)?:\/\//i.test(body)) throw new Error(`Possible credential in ${name}`);
  const sections = body.split(/^## /m).map((s) => s.trim()).filter(Boolean);
  sections.forEach((section, index) => {
    const [heading, ...lines] = section.split('\n');
    if (section.length > 5000) throw new Error(`Knowledge section too long: ${name} / ${heading}`);
    chunks.push({ ...meta, source: meta.sectionSources?.[heading] ?? meta.source, id: `${meta.documentId}-${index}`, title: `${meta.title} — ${heading}`, path: `docs/knowledge/${name}`, text: lines.join('\n').trim() });
  });
}
if (!chunks.length) throw new Error('No approved knowledge documents');
const output = `// Generated by scripts/build-knowledge.mjs from approved docs/knowledge/*.md.\nexport const KNOWLEDGE_CHUNKS = ${JSON.stringify(chunks, null, 2)} as const;\n`;
const target = path.join(root, 'backend/src/shared/knowledge.generated.ts');
let existing = '';
try { existing = readFileSync(target, 'utf8'); } catch { /* First build. */ }
if (existing !== output) writeFileSync(target, output, 'utf8');
console.log(`Knowledge index: ${chunks.length} approved sections`);
syncFrontendShared();
